# -*- coding: utf-8 -*-
"""
⑥ 방법론 탭 — 시스템이 '어떤 로직으로, 어떤 근거로' 작동하는지 설명.

코드(objectives.py, constraints.py)의 실제 수식·상수와 일치하도록 작성.
교수/심사위원이 5분 안에 시스템의 논리를 이해하는 것이 목표.
"""

import streamlit as st


def render_methodology():
    st.subheader("방법론 — 이 시스템이 작동하는 원리와 근거")
    st.caption("도심 협소대지 타워크레인 배치를 '제3자 안전위험 vs 양중 효율'의 "
               "다목적 최적화 문제로 정식화했습니다. 아래는 그 수식·제약·"
               "알고리즘의 공학적 근거입니다.")

    # ────────────────────────────────────────────────────────────
    # 1. 문제 정의
    # ────────────────────────────────────────────────────────────
    with st.expander("1. 문제 정의 — 왜 다목적 최적화인가", expanded=True):
        st.markdown(
            "타워크레인을 **안전한 곳**에 두면 양중 동선이 길어져 **공기**가 늘고, "
            "**효율적인 곳**에 두면 선회반경이 도로·인접 건물을 더 많이 덮어 "
            "**제3자 위험**이 커집니다. 두 목표는 본질적으로 상충합니다.\n\n"
            "따라서 하나의 정답이 아니라, 두 목표 사이의 **타협 곡선(Pareto front)** 을 "
            "구하고 그 중 균형점(knee)을 추천하는 **다목적 최적화**가 타당합니다.\n\n"
            "- **결정변수**: 크레인 위치(x, y), 기종, 지브 길이, 마스트 높이\n"
            "- **목적함수**: F1(제3자 안전위험) ↓, F2(양중 사이클타임) ↓\n"
            "- **제약**: 9개 공학적 제약(G1~G9) 모두 충족"
        )

    # ────────────────────────────────────────────────────────────
    # 2. F1 — 제3자 안전위험
    # ────────────────────────────────────────────────────────────
    with st.expander("2. F1 — 제3자 안전위험 (낮을수록 안전)"):
        st.markdown(
            "위험 = 발생가능성 × 결과의 심각도 라는 **ISO 31000:2018** 위험 정의를 "
            "타워크레인 선회면에 적용했습니다."
        )
        st.latex(r"F_1 = \left(\sum_{\text{자재}} N_{\text{자재}} \times P_{\text{base}} "
                 r"\times R_{\text{자재}}\right) \times \sum_{z} V_z \times A_z")
        st.markdown(
            "- $N_{자재}$ : 자재별 양중 횟수\n"
            "- $P_{base}$ : 사이클당 사고 발생확률 = **1×10⁻⁴** (갱폼 3톤 기준)\n"
            "- $R_{자재}$ : 자재별 위험계수 (무겁고 다루기 어려울수록 큼)\n"
            "- $V_z$ : 구역별 **취약성 가중치**\n"
            "- $A_z$ : 선회면이 그 구역을 덮는 **면적**\n\n"
            "**취약성 가중치 (V_z)** — KOSHA KRAS 위험성평가 + CIRIA C703 근거:"
        )
        st.markdown(
            "| 구역 | 가중치 | 근거 |\n"
            "|---|---|---|\n"
            "| 도로 | **5.0** | 불특정 보행자·차량, 통제 불가 |\n"
            "| 인접 주거 | **3.0** | 거주자 상시 체류 |\n"
            "| 자기 부지 | 0.5 | 통제된 공사 관계자만 |\n"
            "| 신축 건물 | 0.5 | 동일 |\n"
            "| 공지(빈터) | 0.5 | 체류자 적음 |"
        )
        st.info("핵심: F1은 **절대 안전등급이 아니라 배치 간 상대 비교 지표**입니다. "
                "F1=100이 좋은지 나쁜지가 아니라, 다른 배치와 비교해 더 낮은지가 의미입니다.")

    # ────────────────────────────────────────────────────────────
    # 3. F2 — 양중 사이클타임
    # ────────────────────────────────────────────────────────────
    with st.expander("3. F2 — 양중 사이클타임 (낮을수록 빠름)"):
        st.markdown(
            "야적장에서 자재를 들어 양중점까지 옮기고 돌아오는 **한 사이클**의 "
            "시간을, 모든 양중점·자재에 대해 합산합니다."
        )
        st.latex(r"F_2 = \frac{1}{\eta}\sum_{\text{점}, \text{자재}} "
                 r"N \times T_{\text{cycle}}")
        st.markdown(
            "한 사이클은 다음으로 구성됩니다:\n\n"
            "**결박 → 양중(상승) → 수평이동(선회/반경) → 하강 → 해제 → "
            "공하중 복귀**\n\n"
            "- 수평이동 시간 = max(선회시간, 반경이동시간) "
            "(선회와 트롤리/러핑은 동시 동작)\n"
            "- 자재가 무거울수록 호이스트 속도가 느려지는 것까지 반영\n"
            "- $\\eta$ : **가동률 = 0.62** — 날씨·간섭·대기 등으로 인한 "
            "실가동 손실 반영 (달력시간 환산)\n\n"
            "이 가동률 때문에 '순수 작업시간'과 '실제 소요일수'가 다릅니다."
        )

    # ────────────────────────────────────────────────────────────
    # 4. 9개 제약
    # ────────────────────────────────────────────────────────────
    with st.expander("4. 9개 공학적 제약 (G1~G9) — 법령·기준 근거"):
        st.markdown(
            "최적화는 아래 9개 제약을 **모두 만족하는** 배치 중에서만 해를 찾습니다. "
            "코드 내부 표기(C)와 보고서 표기(G)의 대응은 다음과 같습니다."
        )
        st.markdown(
            "| 번호 | 제약 | 내용 | 근거 |\n"
            "|---|---|---|---|\n"
            "| G1 | 인양능력 | 모든 양중점에서 인양능력 ≥ 요구하중 | 제조사 Load Chart (FEM 1.001) |\n"
            "| G2 | 인접건물 이격 | 선회면–인접건물 ≥ **0.6 m** | KOSHA GUIDE C-104-2020 |\n"
            "| G3 | 본체 침범 | 인접건물 footprint 침범 금지 | KOSHA GUIDE C-104 |\n"
            "| G4 | 풍하중 모멘트 | 전도모멘트 ≤ 허용모멘트 | KDS 41 12 00, FEM 1.001 |\n"
            "| G5 | 도달거리 | 전 양중점 도달(사각지대 0) | 기하 조건 |\n"
            "| G6 | 후크 높이 | 마스트 ≥ 건물높이 + **7 m** | 시공 안전여유 |\n"
            "| G7 | 설치 영역 | 내부/외부 설치 영역 적합 | KOSHA, 클라이밍 공법 |\n"
            "| G8 | 벽체정착 | Wall-tie 가능거리 이내 | 제조사 기준 |\n"
            "| G9 | 공중 침범 | 선회면 ⊆ 허용영역(±15%) | 민법 상공권 + 도로점용 |"
        )
        st.markdown(
            "**허용영역(ALLOWED_AREA)** = 자기 부지 ∪ 점용허가 도로 ∪ 빈 인접대지 "
            "∪ 상공권 동의를 받은 인접 건물.\n\n"
            "협소대지에서는 선회반경이 대지를 벗어나는 것이 통상적이므로, "
            "도로점용 허가와 인접 상공권 동의를 통해 작업 가능한 공역을 정의합니다. "
            "이때 마스트가 인접 건물보다 **5 m** 이상 높아 지브가 그 위를 안전하게 "
            "통과하면, 평면 이격(G2)을 면제합니다.\n\n"
            "> 참고: 코드 내부에서는 8개 검사 함수(C1, C2-1, C2-3, C3-1, C4-1, "
            "C5~C8)로 구현되며, 이 중 C2-3(공역 검사)이 보고서의 G3(본체 침범)와 "
            "G9(공중 침범)를 함께 담당합니다. 따라서 검사 함수는 8개, 공학 요건은 "
            "9개로 대응합니다."
        )

    # ────────────────────────────────────────────────────────────
    # 5. 러핑 크레인과 작업반경 (핵심 모델링)
    # ────────────────────────────────────────────────────────────
    with st.expander("5. 왜 러핑 크레인인가 — 협소대지 핵심 모델링"):
        st.markdown(
            "**T형(해머헤드)** 크레인은 카운터지브가 무풍 시 자유회전(weather-vane)하여 "
            "선회면 전체가 360° 원이 됩니다. 협소대지에서는 이 원이 대지를 크게 "
            "벗어나 부적합합니다.\n\n"
            "**러핑(luffing)** 크레인은 지브 각도를 세워(최대 약 86°) **작업 반경을 "
            "줄일 수 있습니다.** 그래서 인접 공역 침범이 제한되는 좁은 도심 현장의 "
            "표준 선택입니다.\n\n"
            "이 시스템은 러핑의 특성을 정확히 반영합니다 — 침범·이격 계산 시 "
            "지브 길이 전체가 아니라 **모든 양중점에 닿는 데 필요한 실제 작업 반경**"
            "(가장 먼 양중점 + 후크 여유 1.5 m)을 사용합니다. 지브를 필요 이상으로 "
            "눕히지 않는 실제 운용과 일치합니다.\n\n"
            "후보 기종: **Potain MR 160C**, **Liebherr 280 HC-L** — 둘 다 도심 "
            "협소·고층 현장에서 널리 쓰이는 러핑 모델입니다."
        )

    # ────────────────────────────────────────────────────────────
    # 6. NSGA-II
    # ────────────────────────────────────────────────────────────
    with st.expander("6. NSGA-II — 왜 이 알고리즘인가"):
        st.markdown(
            "**NSGA-II**(Non-dominated Sorting Genetic Algorithm II)는 다목적 "
            "최적화의 표준 알고리즘입니다.\n\n"
            "- **비지배 정렬**: F1·F2 둘 다 동시에 더 나은 해가 없는 '비지배해'들을 "
            "찾아 Pareto front를 구성합니다.\n"
            "- **혼잡도 거리**: 해들이 곡선 위에 고르게 분포하도록 유지합니다.\n"
            "- **knee point**: Pareto front에서 두 목표의 균형이 가장 좋은 지점을 "
            "추천안으로 선정합니다 (정규화 후 원점에 가장 가까운 해).\n\n"
            "단일 가중합(weighted sum) 방식과 달리, 가중치를 임의로 정하지 않고 "
            "**상충 구조 전체를 제시**한 뒤 의사결정자가 선택할 수 있게 합니다."
        )

    # ────────────────────────────────────────────────────────────
    # 7. 신뢰성 검증
    # ────────────────────────────────────────────────────────────
    with st.expander("7. 결과의 신뢰성 — 어떻게 검증했는가"):
        st.markdown(
            "유전 알고리즘은 무작위성이 있으므로, 결과가 우연이 아님을 "
            "여러 층위로 검증합니다 (⑤ 검증·민감도 탭).\n\n"
            "- **다중 seed 합의**: 서로 다른 난수로 독립 실행해 추천 위치가 "
            "일관되게 수렴하는지 확인 (검증 부지에서 수 m 이내 수렴).\n"
            "- **민감도 분석**: 취약성 가중치·사고확률·가동률을 ±50% 변동시켜도 "
            "결과가 안정적인지 확인 (최대 민감도 약 18%로 20% 미만).\n"
            "- **Monte Carlo 강건성**: 여러 파라미터를 동시에 무작위 변동시켜 "
            "200회 반복해도 추천이 안정적으로 유지되는지 확인.\n\n"
            "이로써 '특정 가정에 의존한 우연한 결과'가 아니라 **재현 가능하고 "
            "강건한 추천**임을 보입니다."
        )

    # ────────────────────────────────────────────────────────────
    # 8. 한계
    # ────────────────────────────────────────────────────────────
    with st.expander("8. 한계와 적용 범위 (정직한 고지)"):
        st.markdown(
            "- 본 도구는 **설계 초기 단계의 의사결정 보조 도구**입니다. 실제 설치 시 "
            "현장 측량·지반조사·관련 인허가 검토가 병행되어야 합니다.\n"
            "- F1은 절대 안전등급이 아니라 **배치 간 상대 비교 지표**입니다.\n"
            "- 위성영상과 지적도의 정합에는 ±수 m 오차가 있을 수 있으나, 모델은 "
            "절대좌표가 아닌 **상대 거리**만 사용하므로 결과에 미치는 영향은 "
            "제한적입니다.\n"
            "- 인접 건물의 높이·층수는 현재 사용자 입력에 의존합니다 "
            "(공공 데이터 자동연계는 향후 과제)."
        )

    # ────────────────────────────────────────────────────────────
    # 참고문헌
    # ────────────────────────────────────────────────────────────
    with st.expander("참고문헌 · 출처"):
        st.markdown(
            "- ISO 31000:2018 — Risk management 위험 정의 구조\n"
            "- KOSHA GUIDE C-104-2020 — 타워크레인 설치·해체 안전\n"
            "- KOSHA GUIDE C-50 — 양중작업 안전\n"
            "- KOSHA KRAS — 위험성평가 기법\n"
            "- KDS 41 12 00 — 건축구조기준(하중)\n"
            "- FEM 1.001 — 크레인 설계기준 (제조사 Load Chart)\n"
            "- CIRIA C703 — Crane stability 가이드\n"
            "- 손승현 외 (2022), 한국건축시공학회\n"
            "- Potain MR 160C / Liebherr 280 HC-L 공식 제조사 데이터시트"
        )
